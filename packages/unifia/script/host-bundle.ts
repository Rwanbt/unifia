// The Browser host runs under Node, not inside the sidecar (ADR-089, #279), so it
// ships as one JavaScript file the sidecar writes out on first use. Playwright
// stays external: it is installed beside the file by BrowserHostRuntime.
//
// Both sidecar builds need it: script/build.ts for the desktop binary and
// scripts/bundle-mobile.mjs for the Android bundle, which runs this file directly.
import path from "node:path"

export async function generateBrowserHostBundle(packageDirectory: string): Promise<void> {
  const hostBuild = await Bun.build({
    entrypoints: [path.join(packageDirectory, "../browser-runtime/src/host/host-entry.ts")],
    target: "node",
    format: "esm",
    external: ["playwright", "playwright-core"],
  })
  if (!hostBuild.success || hostBuild.outputs.length !== 1) {
    throw new Error(`Browser host bundle failed: ${hostBuild.logs.join("\n")}`)
  }
  await Bun.write(
    path.join(packageDirectory, "src/browser/host-bundle.generated.js"),
    `// Auto-generated by script/host-bundle.ts - do not edit\nexport const source = ${JSON.stringify(await hostBuild.outputs[0]!.text())}\n`,
  )
  await Bun.write(
    path.join(packageDirectory, "src/browser/host-bundle.generated.d.ts"),
    `// Auto-generated by script/host-bundle.ts - do not edit\nexport declare const source: string\n`,
  )
}

if (import.meta.main) {
  await generateBrowserHostBundle(path.resolve(import.meta.dir, ".."))
  console.log("Generated Browser host bundle")
}
