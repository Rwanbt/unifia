/**
 * Development-time lock generator for the Debian-based toolchains.
 *
 * Trust chain: the suite's InRelease is verified against the Ubuntu archive keyring with gpgv (the
 * check apt performs); its SHA256 list gives the digest and size of Packages.xz; that index is
 * checked against them; each package is then pinned by the sha256 the index records for it. The
 * runtime never reads an index. It only downloads the packages written into src/toolchain/locks.
 *
 * Run from packages/unifia: bun script/toolchain-lock.ts
 */
import { createHash } from "node:crypto"
import { mkdtemp, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import path from "node:path"
import { parseIndex, resolve } from "../src/toolchain/debian"
import { capture } from "../src/toolchain/exec"

const SUITE = "noble"
const KEYRING = "/usr/share/keyrings/ubuntu-archive-keyring.gpg"
// Packages the host supplies: the test vehicle takes the glibc and C++ runtime from its sysroot.
const HOST = ["libc6", "libgcc-s1", "libstdc++6"]
const ROOTS: Record<string, string[]> = { "python3": ["python3"], "git": ["git"] }
const SOURCES = [
  { arch: "arm64", platform: "linux-arm64", base: "https://ports.ubuntu.com/ubuntu-ports" },
  { arch: "amd64", platform: "linux-x64", base: "https://archive.ubuntu.com/ubuntu" },
]

async function fetchBytes(url: string) {
  const res = await fetch(url, { redirect: "follow" })
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`)
  return new Uint8Array(await res.arrayBuffer())
}

const sha256 = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex")

// The SHA256 section of a Release file lists "<sha256> <size> <path>" for every index file. Other
// sections (MD5Sum, SHA1, SHA512) have the same shape, so only the lines under "SHA256:" count.
function indexEntry(release: string, rel: string) {
  const lines = release.split("\n")
  const start = lines.findIndex((item) => item.trim() === "SHA256:")
  if (start < 0) throw new Error("Release has no SHA256 section")
  const section: string[] = []
  for (const item of lines.slice(start + 1)) {
    if (!item.startsWith(" ")) break
    section.push(item)
  }
  const line = section.find((item) => item.trim().split(/\s+/)[2] === rel)
  if (line === undefined) throw new Error(`no SHA256 entry for ${rel}`)
  const [digest, size] = line.trim().split(/\s+/)
  return { digest: digest!, size: Number(size) }
}

type Locked = { name: string; version: string; url: string; size: number; sha256: string }
type Lock = { verified: { suite: string; arch: string; packagesSha256: string; packagesSize: number }; packages: Record<string, Locked[]> }

async function lockFor(dir: string, source: (typeof SOURCES)[number]): Promise<Lock> {
  const base = `${source.base}/dists/${SUITE}`
  const inRelease = path.join(dir, `InRelease-${source.arch}`)
  await writeFile(inRelease, await fetchBytes(`${base}/InRelease`))
  const verified = await capture(["gpgv", "--keyring", KEYRING, inRelease])
  if (verified.code !== 0) throw new Error(`InRelease signature rejected for ${source.arch}: ${verified.stderr}`)
  const release = await Bun.file(inRelease).text()

  const rel = `main/binary-${source.arch}/Packages.xz`
  const want = indexEntry(release, rel)
  const packed = await fetchBytes(`${base}/${rel}`)
  if (packed.byteLength !== want.size || sha256(packed) !== want.digest) throw new Error(`index ${rel} does not match the signed Release`)
  const packedFile = path.join(dir, `Packages-${source.arch}.xz`)
  await writeFile(packedFile, packed)
  const text = await capture(["xz", "-dc", packedFile])
  const index = parseIndex(text.stdout)

  const packages: Record<string, Locked[]> = {}
  for (const [id, roots] of Object.entries(ROOTS)) {
    const resolved: Locked[] = resolve(index, roots, HOST).map((item) => ({
      name: item.name,
      version: item.version,
      url: `${source.base}/${item.filename}`,
      size: item.size,
      sha256: item.sha256,
    }))
    packages[id] = resolved
  }
  return { verified: { suite: SUITE, arch: source.arch, packagesSha256: want.digest, packagesSize: want.size }, packages }
}

const work = await mkdtemp(path.join(tmpdir(), "toolchain-lock-"))
for (const source of SOURCES) {
  const lock = await lockFor(work, source)
  for (const id of Object.keys(ROOTS)) {
    const packages = lock.packages[id] ?? []
    const body = packages
      .map((item) => `  { name: ${JSON.stringify(item.name)}, version: ${JSON.stringify(item.version)}, url: ${JSON.stringify(item.url)}, size: ${item.size}, sha256: ${JSON.stringify(item.sha256)} },`)
      .join("\n")
    const { verified } = lock
    const file = `// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Unifia contributors\n\n// Generated by script/toolchain-lock.ts from the ${verified.suite} ${verified.arch} index\n// (Packages.xz sha256 ${verified.packagesSha256}, ${verified.packagesSize} bytes, signed InRelease verified\n// with the Ubuntu archive keyring). Do not edit by hand: regenerate instead.\nexport const packages = [\n${body}\n]\n`
    await writeFile(path.join(import.meta.dir, "..", "src", "toolchain", "locks", `${id}-${source.platform}.ts`), file)
    console.log(`${id} ${source.platform}: ${packages.length} packages, ${packages.reduce((sum, item) => sum + item.size, 0)} bytes`)
  }
}
