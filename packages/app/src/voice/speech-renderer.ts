/** Localised phrase lookup; unknown languages fall back to English (the
 * Python reference does `PHRASES.get(language) or PHRASES["en"]`). */
export function phrase(language: string, key: PhraseKey, values: Record<string, string | number> = {}): string {
  const table = PHRASES[language as SpeechLanguage] ?? PHRASES.en
  return table[key].replace(/\{(\w+)\}/g, (whole, name: string) => String(values[name] ?? whole))
}

/** Secrets are matched before anything else so no later rule can leak them. */
const SECRET_PATTERNS: readonly RegExp[] = [
  /-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?(-----END [A-Z ]*PRIVATE KEY-----|$)/g,
  /\b(?:sk|pk|rk)-[A-Za-z0-9_-]{16,}\b/g,
  /\bsk-ant-[A-Za-z0-9_-]{16,}\b/g,
  /\bgh[pousr]_[A-Za-z0-9]{20,}\b/g,
  /\bgithub_pat_[A-Za-z0-9_]{20,}\b/g,
  /\bxox[abprs]-[A-Za-z0-9-]{10,}\b/g,
  /\bAKIA[0-9A-Z]{16}\b/g,
  /\bAIza[0-9A-Za-z_-]{30,}\b/g,
  /\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\b/g,
  /\bbearer\s+[A-Za-z0-9._~+/-]{12,}=*/gi,
  /\b(?:password|passwd|pwd|secret|token|api[_-]?key|access[_-]?key|private[_-]?key|client[_-]?secret)\s*[:=]\s*["']?[^\s"',;]{4,}/gi,
  /\b[a-z][a-z0-9+.-]*:\/\/[^\s:/@]+:[^\s@/]+@/gi,
]
const URL = /\b(?:https?|wss?|ftp):\/\/[^\s)>\]]+|\bwww\.[^\s)>\]]+/gi
const HASH = /\b(?=[0-9a-fA-F]*[a-fA-F])(?=[0-9a-fA-F]*\d)[0-9a-fA-F]{12,64}\b/g
const UUID = /\b[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b/g
const PATH = /(?<![\w/])(?:[A-Za-z]:\\|~?\/|\.{1,2}\/)?(?:[\w.@-]+[/\\]){2,}([\w.@-]+)/g
const INLINE_CODE = /`([^`\n]*)`/g
const MD_LINK = /!?\[([^\]]*)\]\(([^)]*)\)/g
const EMPHASIS = /(\*\*|__|\*|_|~~)(?=\S)(.+?)(?<=\S)\1/g
const HEADING = /^\s{0,3}#{1,6}\s+/gm
const QUOTE = /^\s{0,3}>\s?/gm
const LIST_MARKER = /^\s*(?:[-*+]|\d+[.)])\s+/gm
const HTML_TAG = /<\/?[A-Za-z][^>]*>/g
const STACK_LINE =
  /^\s*(?:at\s+\S+\s*\(|at\s+[\w.$<>]+:\d+|File "[^"]+", line \d+|Traceback \(most recent call last\)|\w+(?:Error|Exception):\s|panicked at|thread '.*' panicked)/
const DIFF_LINE = /^(?:@@ .* @@|\+\+\+ |--- |diff --git |index [0-9a-f]+\.\.)/
const JSONISH = /^\s*[\[{].*["'][\w-]+["']\s*:.*$|^\s*["'][\w-]+["']\s*:\s*/
const SPLIT_LINES = /\r\n|[\n\r\v\f\x1c\x1d\x1e\x85\u2028\u2029]/
const HAS_WORD = /[\p{L}\p{N}_]/u

export function redactSecrets(text: string, language: string): string {
  const replacement = phrase(language, "secret")
  let out = text
  for (const pattern of SECRET_PATTERNS) out = out.replace(pattern, () => replacement)
  return out
}

function isUnspeakableLine(line: string): boolean {
  const stripped = line.trim()
  if (!stripped) return false
  if (STACK_LINE.test(stripped) || DIFF_LINE.test(stripped) || JSONISH.test(stripped)) return true
  // Long tokens without spaces (minified code, base64, logs) are noise aloud.
  let longest = 0
  for (const token of stripped.split(/\s+/)) longest = Math.max(longest, token.length)
  if (longest > 60) return true
  let symbols = 0
  for (const character of stripped) if ("{}[]();=<>|&$\\".includes(character)) symbols++
  return stripped.length > 12 && symbols / stripped.length > 0.18
}

/** Return speakable text for one prose segment, or null to skip it. */
export function render(text: string, language: string): string | null {
  text = redactSecrets(text, language)
  const keptLines = text.split(SPLIT_LINES).filter((line) => !isUnspeakableLine(line))
  if (keptLines.length === 0) return text.trim() ? phrase(language, "details") : null
  text = keptLines.join("\n")
  text = text.replace(HTML_TAG, " ")
  text = text.replace(MD_LINK, (_match, label: string) => label || phrase(language, "link"))
  text = text.replace(URL, () => phrase(language, "link"))
  text = text.replace(UUID, "")
  text = text.replace(INLINE_CODE, (_match, code: string) => (code.length <= 32 ? code : ""))
  text = text.replace(PATH, (_match, last: string | undefined) => last ?? "")
  text = text.replace(HASH, "")
  text = text.replace(HEADING, "")
  text = text.replace(QUOTE, "")
  text = text.replace(LIST_MARKER, "")
  for (let pass = 0; pass < 2; pass++) text = text.replace(EMPHASIS, (_match, _marker, inner: string) => inner)
  text = text.replaceAll("`", "").replaceAll("|", " ")
  text = text.replace(/\s+/g, " ").trim()
  text = text.replace(/\s+([,.;:!?])/g, "$1")
  text = text.replace(/\(\s*\)|\[\s*\]/g, "").trim()
  if (!HAS_WORD.test(text)) return null
  return text
}

/** The reference pipeline's `segment_text`: markers become localised
 * phrases, prose goes through `render`. Returns null when nothing should be
 * spoken for this segment. */
export function renderSegment(segment: SpeechSegment, language: string): string | null {
  if (segment.kind === "code") return phrase(language, "code")
  if (segment.kind === "table") return phrase(language, "table")
  if (segment.kind === "list_rest") return phrase(language, "list_rest", { count: segment.count })
  return render(segment.text, language)
}
