/** Turn assistant Markdown into text that is safe and pleasant to speak.
 *
 * TypeScript port of the Python reference in
 * `packages/voice-host/voice_host/live/renderer.py`. Speech is a disclosure
 * channel: anything spoken can be overheard or recorded. The renderer
 * therefore removes secrets outright and reduces content that is unreadable
 * aloud (code, JSON, diffs, stack traces, hashes, long URLs) to a short
 * spoken reference to the conversation, where the full text remains.
 *
 * Parity with the reference implementation is enforced by
 * `packages/voice-core/fixtures/speech-text-parity.json` (generated by
 * `scripts/voice/generate-speech-fixtures.py`, asserted from both the TS and
 * Python suites).
 */
